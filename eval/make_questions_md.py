"""Regenerate eval/QUESTIONS.md from eval/questions.json.

    python eval/make_questions_md.py
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

HERE = Path(__file__).parent

LABELS = {
    "policy": "Rules, regulations and calendar (RAG)",
    "schedule": "Timetable and course offerings (CSV tools)",
    "email": "Email drafting and instructor lookup",
    "out_of_scope": "Out of scope (must refuse and log)",
}


def main() -> None:
    spec = json.loads((HERE / "questions.json").read_text(encoding="utf-8"))
    questions = spec["questions"]
    counts = Counter(q["category"] for q in questions)

    lines = [
        f"# Evaluation questions ({len(questions)})",
        "",
        f"Set `{spec['set_name']}`, generated from `questions.json` by "
        "`eval/make_questions_md.py`. Do not edit this file by hand.",
        "",
        " · ".join(f"{LABELS[c].split(' (')[0]}: {n}" for c, n in counts.items()),
        "",
    ]
    for category in LABELS:
        rows = [q for q in questions if q["category"] == category]
        if not rows:
            continue
        lines += [f"## {LABELS[category]}", ""]
        for q in rows:
            lines += [
                f"**{q['id']}. {q['question']}**",
                "",
                f"- Reference answer: {q['reference_answer']}",
                f"- Expected route: `{q['expected_route']}`",
            ]
            if q["groundedness_doc_ids"]:
                lines.append("- Must cite one of: " + ", ".join(f"`{d}`" for d in q["groundedness_doc_ids"]))
            if q.get("refusal_acceptable"):
                lines.append("- An honest refusal is also scored correct (the corpus only partly answers this).")
            lines.append("")
    (HERE / "QUESTIONS.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {HERE / 'QUESTIONS.md'}")


if __name__ == "__main__":
    main()
